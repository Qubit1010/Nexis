#!/usr/bin/env python3
"""BUILD mode: write the artifacts, not another description of them.

AUDIT mode ends at a diagnosis. BUILD mode ends at files someone can deploy - a corrected
robots.txt, the URL list a clean sitemap should contain, a flattened redirect map, the two
JSON-LD blocks worth having, and either a corrected hreflang set or a written record that it
does not apply.

Two rules this module holds to, both of which are easy to break and embarrassing when broken:

  1. **Never emit an artifact that fails this skill's own checks.** A generated robots.txt
     that omits the sitemap directive, or a generated sitemap containing a 404, would be an
     audit shipping the defect it just charged to find. Every artifact here is built from
     the same rules technical.py enforces, and `--verify` re-runs those rules against what
     was written.

  2. **Never invent a fact.** `sameAs` needs the client's real profile URLs and there is no
     way to know them from a crawl, so they are emitted as marked placeholders that fail
     loudly rather than plausible guesses that ship silently. Same for the Organization
     legal name. A placeholder someone must fill is honest; a fabricated LinkedIn URL in a
     client's structured data is not.

Nothing here is written to the live site. These are files in an output directory plus a
README explaining what each one is and where it goes.
"""
