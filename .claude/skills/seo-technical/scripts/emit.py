# --------------------------------------------------------------------------- robots.txt

def build_robots(g: dict) -> tuple[str, list[str]]:
    """A corrected robots.txt plus the list of changes made, so nothing lands unexplained."""
    rb = g.get("robots") or {}
    origin = (g.get("origin") or "").rstrip("/")
    changes: list[str] = []

    keep = [d for d in (rb.get("disallows") or [])
            if d and d != "/" and not re.search(
                r"\.(css|js)|/wp-includes|/wp-content/themes|/assets|/static", d, re.I)]
    dropped = [d for d in (rb.get("disallows") or []) if d not in keep]
    if "/" in dropped:
        changes.append("Removed `Disallow: /` - it was blocking the entire site (course/21).")
    for d in dropped:
        if d != "/":
            changes.append(f"Removed `Disallow: {d}` - it blocks CSS or JS, so Google evaluates "
                           "a broken render of the page (course/21).")

    sitemaps = list(rb.get("sitemaps") or [])
    if not sitemaps:
        sitemaps = [f"{origin}/sitemap.xml"]
        changes.append("Added the Sitemap: directive, which was missing (course/21).")

    declared = rb.get("ai_policy_declared") or {}
    if not declared:
        changes.append("Added an explicit AI crawler policy. Previously undeclared, which is a "
                       "default rather than a decision (course/21 -> course/40).")
    if rb.get("mentions_deprecated_anthropic_ai"):
        changes.append("Dropped the deprecated `anthropic-ai` agent. The live agents are "
                       "ClaudeBot (training) and Claude-SearchBot (retrieval).")

    lines = ["# robots.txt - generated by seo-technical. Review before deploying.",
             "# Must return HTTP 200. A 5xx here stops Googlebot crawling the whole site.",
             "", "User-agent: *", "Allow: /"]
    lines += [f"Disallow: {d}" for d in keep]
    lines += ["", AI_POLICY.rstrip(), ""]
    lines += [f"Sitemap: {s}" for s in sitemaps]
    lines.append("")

    if g.get("skipped_by_robots"):
        changes.append(
            f"NOTE: {len(g['skipped_by_robots'])} URL(s) were disallowed at crawl time. If any "
            "of them also carry `noindex`, that combination is broken - a disallowed URL is "
            "never fetched, so the noindex is never read, and the URL can stay indexed as a "
            "bare link forever. Pick one: allow crawling and keep noindex, or disallow and "
            "accept the bare URL (course/21).")
    return "\n".join(lines), changes


# --------------------------------------------------------------------------- sitemap

def build_sitemap(g: dict) -> tuple[str, list[str], list[str]]:
    """(xml, included, excluded-with-reason). Only what course/22 permits."""
    # Every crawled URL, not just the healthy ones. _live() drops non-200s, and filtering
    # first would silently swallow the 404s and redirects this file exists to explain the
    # exclusion of - the excluded list is half the deliverable.
    pages = g.get("pages") or {}
    disallowed = set(g.get("sitemap_urls_disallowed") or [])
    included, excluded = [], []

    for u, p in sorted(pages.items()):
        why = None
        ctype = p.get("content_type") or ""
        if ctype and not ctype.startswith("text/html"):
            why = f"not HTML ({ctype})"
        elif p.get("status") != 200:
            why = f"HTTP {p['status']}"
        elif p.get("redirect_chain"):
            why = f"redirects to {p.get('final_url')}"
        elif _has_noindex(p):
            why = "noindex"
        elif p.get("canonical") and crawl.normalize_url(p["canonical"]) != crawl.normalize_url(u):
            why = f"canonicalized to {p['canonical']}"
        elif u in disallowed:
            why = "disallowed in robots.txt"
        (excluded.append(f"{u} - {why}") if why else included.append(u))

    # A capped crawl means this file is a SUBSET, and deploying a subset silently drops every
    # URL the crawl never reached. On the first live run that was 25 of 38 submitted URLs -
    # a generated artifact that would have removed 13 pages from the client's sitemap.
    stats = g.get("stats") or {}
    submitted = len(g.get("sitemap_urls_submitted") or [])
    warning = ""
    if stats.get("hit_cap") or submitted > len(included) + len(excluded):
        warning = (
            f'\n<!-- INCOMPLETE - DO NOT DEPLOY AS-IS.\n'
            f'     The crawl stopped at its {stats.get("cap")}-page cap, so this file covers\n'
            f'     only the {len(included)} URL(s) it verified. The site submits {submitted}.\n'
            f'     Deploying this would remove every unverified URL from the sitemap.\n'
            f'     Re-run: crawl.py <url> --max-pages {max(submitted * 2, 300)} --yes --refresh\n'
            f'     then emit.py again. -->\n')

    body = "\n".join(f"  <url>\n    <loc>{u}</loc>\n  </url>" for u in included)
    xml = ('<?xml version="1.0" encoding="UTF-8"?>\n'
           '<!-- Generated by seo-technical. Only 200-status, canonical, indexable URLs.\n'
           '     Add a real <lastmod> per URL from your CMS: Google uses it as a recrawl\n'
           '     hint, and one date across every URL is a recognised bad pattern that\n'
           '     destroys its value. priority and changefreq are ignored - do not add them. -->'
           f'{warning}\n'
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
           f"{body}\n</urlset>\n")
    return xml, included, excluded


# --------------------------------------------------------------------------- redirects

def build_redirects(g: dict) -> tuple[str, list[str]]:
    """A flattened one-hop map: every source pointed straight at its final destination."""
    pages = g.get("pages") or {}
    rows = ["from,to,was,note"]
    notes: list[str] = []

    for u, p in sorted(pages.items()):
        hops = p.get("redirect_chain") or []
        if not hops:
            continue
        final = p.get("final_url") or u
        codes = "->".join(str(h["status"]) for h in hops)
        note = []
        if len(hops) > 1:
            note.append(f"flattened {len(hops)} hops to 1")
        if any(h["status"] in (302, 303, 307) for h in hops):
            note.append("was temporary, now 301")
        rows.append(f"{u},{final},{codes},{'; '.join(note) or 'unchanged'}")

    stale = []
    redirecting = {u for u, p in pages.items() if p.get("redirect_chain")}
    for u, p in pages.items():
        for tgt in p.get("internal_outlinks") or []:
            if crawl.normalize_url(tgt) in redirecting:
                stale.append(f"{u} -> {tgt}")
    if stale:
        notes.append(f"{len(stale)} internal link(s) point at a redirect. Repoint them at the "
                     "final destination - a redirect should be a fallback for external links, "
                     "not a routine internal hop (course/24).")
    if len(rows) == 1:
        notes.append("No redirects found in the crawl, so this map is empty. That is the "
                     "desired state.")
    return "\n".join(rows) + "\n", notes


# --------------------------------------------------------------------------- schema

def build_schema(g: dict) -> tuple[str, str, list[str]]:
    """Organization and BreadcrumbList: the highest-value, lowest-effort pair (course/30)."""
    origin = (g.get("origin") or "").rstrip("/")
    pages = _live(g.get("pages") or {})
    # Both spellings: normalize_url keeps "/" and "" distinct on purpose (course/23), so a
    # crawl seeded without a trailing slash keys the homepage without one.
    home = pages.get(crawl.normalize_url(origin + "/")) or \
        pages.get(crawl.normalize_url(origin)) or {}
    # The organization name is a PLACEHOLDER, never derived from the homepage title.
    # Splitting "Festival | Example Faire | Example City" on the first pipe yields
    # "Festival", which would ship as a client's legal entity name in their structured data.
    # The title is offered in the notes as a hint for a human to read, which is a different
    # thing from a guess.
    title_hint = (home.get("title") or "").strip()

    org = {
        "@context": "https://schema.org",
        "@type": "Organization",
        "@id": f"{origin}/#organization",
        "name": PLACEHOLDER,
        "url": origin + "/",
        "logo": f"{origin}/{PLACEHOLDER}",
        "sameAs": [f"https://www.linkedin.com/company/{PLACEHOLDER}",
                   f"https://www.facebook.com/{PLACEHOLDER}"],
    }

    # A worked example from a real deep URL, so the developer sees the shape against their
    # own paths rather than against example.com.
    deep = next((u for u, p in sorted(pages.items()) if (p.get("depth") or 0) >= 2), None)
    segs = [s for s in urlparse(deep or origin + "/a/b").path.split("/") if s]
    items, acc = [], origin
    for i, seg in enumerate(["Home"] + segs, start=1):
        acc = origin + "/" if i == 1 else acc.rstrip("/") + "/" + segs[i - 2]
        items.append({"@type": "ListItem", "position": i,
                      "name": "Home" if i == 1 else seg.replace("-", " ").title(),
                      "item": acc})
    crumbs = {"@context": "https://schema.org", "@type": "BreadcrumbList",
              "@id": f"{deep or origin}/#breadcrumb", "itemListElement": items}

    notes = [
        f"Organization name is a placeholder on purpose. The homepage title is "
        f"{title_hint!r} - read the real legal or trading name off that, do not let a script "
        "split it on a pipe and guess." if title_hint else
        "Organization name is a placeholder: the homepage was not in the crawl.",
        f"Both blocks go in the <head> as <script type=\"application/ld+json\">. Every "
        f"{PLACEHOLDER} must be replaced with a real value - they are placeholders precisely "
        "so they fail loudly instead of shipping a fabricated profile URL in the client's "
        "structured data.",
        "sameAs is the entity anchor: point it at the real LinkedIn, Crunchbase and social "
        "profiles. This is what course/40's entity work builds on.",
        "BreadcrumbList is a template, not a page. Generate it from the page's real position "
        "in the hierarchy - the example below is built from an actual URL on this site.",
        "Schema is not a ranking factor and the two causal studies of schema against AI "
        "citations found no uplift. Implement it for rich-result eligibility and entity "
        "clarity, and say that to the client rather than promising rankings.",
    ]
    return (json.dumps(org, indent=2), json.dumps(crumbs, indent=2), notes)


# --------------------------------------------------------------------------- hreflang

def build_hreflang(g: dict) -> str:
    pages = _live(g.get("pages") or {})
    tagged = {u: p["hreflang"] for u, p in pages.items() if p.get("hreflang")}
    if not tagged:
        return (
            "# hreflang: not applicable\n\n"
            f"No hreflang was found on any of the {len(pages)} crawled pages, and nothing in "
            "the crawl suggests multiple language or region versions.\n\n"
            "This is a legitimate audit outcome, recorded deliberately rather than left "
            "blank, so nobody implements hreflang later for no reason. Most sites do not need "
            "it: one well-executed site usually outperforms three thin translated ones, and "
            "every hreflang failure mode is silent.\n\n"
            "It becomes applicable only with substantially the same content in multiple "
            "languages, or targeted at multiple countries with real differences - currency, "
            "pricing, shipping, legal terms. Not a currency symbol swap.\n\n"
            "If that changes: use subdirectories (`/de/`) unless the market genuinely demands "
            "a local domain, declare every version on every page including itself, always "
            "include x-default, and verify the return links by hand on three pages.\n")

    lines = ["# hreflang set", "",
             "Every page below must carry its whole set, including a self-reference and "
             "x-default. hreflang is bidirectional: if A declares B, B must declare A, and a "
             "one-way declaration is ignored entirely.", ""]
    for u, alts in sorted(tagged.items()):
        lines.append(f"## {u}")
        lines.append("```html")
        seen = {a.get("lang", "").lower() for a in alts}
        for a in alts:
            lines.append(f'<link rel="alternate" hreflang="{a.get("lang")}" '
                         f'href="{a.get("href")}" />')
        if not any(crawl.normalize_url(a.get("href", "")) == crawl.normalize_url(u) for a in alts):
            lines.append(f'<link rel="alternate" hreflang="{PLACEHOLDER}" href="{u}" />  '
                         '<!-- ADDED: the page was missing its own self-reference -->')
        if "x-default" not in seen:
            lines.append(f'<link rel="alternate" hreflang="x-default" href="{u}" />  '
                         '<!-- ADDED: x-default was missing -->')
        lines += ["```", ""]
    return "\n".join(lines)


# --------------------------------------------------------------------------- write

def emit(g: dict, outdir: Path) -> dict:
    outdir.mkdir(parents=True, exist_ok=True)
    written = {}

    robots, robots_changes = build_robots(g)
    (outdir / "robots.txt").write_text(robots, encoding="utf-8")
    written["robots.txt"] = robots_changes

    xml, included, excluded = build_sitemap(g)
    (outdir / "sitemap.xml").write_text(xml, encoding="utf-8")
    (outdir / "sitemap-excluded.txt").write_text(
        "\n".join(excluded) + "\n" if excluded else "none\n", encoding="utf-8")
    written["sitemap.xml"] = [f"{len(included)} URL(s) included, {len(excluded)} excluded "
                              "(reasons in sitemap-excluded.txt)"]

    csv, redirect_notes = build_redirects(g)
    (outdir / "redirects.csv").write_text(csv, encoding="utf-8")
    written["redirects.csv"] = redirect_notes

    org, crumbs, schema_notes = build_schema(g)
    (outdir / "organization.jsonld").write_text(org, encoding="utf-8")
    (outdir / "breadcrumbs.jsonld").write_text(crumbs, encoding="utf-8")
    written["organization.jsonld / breadcrumbs.jsonld"] = schema_notes

    (outdir / "hreflang.md").write_text(build_hreflang(g), encoding="utf-8")
    written["hreflang.md"] = ["Either the corrected set or a documented not-applicable."]

    readme = [f"# Technical SEO artifacts - {g.get('origin')}", "",
              f"Generated from a crawl of {(g.get('stats') or {}).get('pages_crawled')} pages "
              f"on {g.get('crawled_at')}.", "",
              "Nothing here has been deployed. Review each file, then ship it.", ""]
    for fname, notes in written.items():
        readme += [f"## {fname}", ""]
        readme += [f"- {n}" for n in notes] or ["- No changes needed."]
        readme.append("")
    readme += ["## Order", "",
               "Deploy in tier order (course/21). robots.txt and the sitemap first, because a "
               "page that is not crawled or indexed cannot rank and nothing above that layer "
               "changes it. Redirects next. Schema last - it is the polish, and polishing an "
               "unindexed page is polishing something invisible.", "",
               "After deploying: confirm robots.txt returns 200, resubmit the sitemap in "
               "Search Console, and re-run `crawl.py <url> --refresh` followed by "
               "`technical.py <url>` to verify the findings closed."]
    (outdir / "README.md").write_text("\n".join(readme), encoding="utf-8")
    return written


def verify(outdir: Path) -> list[str]:
    """Re-run this skill's own rules against what was just written. Empty means clean."""
    problems = []
    robots = (outdir / "robots.txt")
    if robots.exists():
        text = robots.read_text(encoding="utf-8")
        groups = crawl._robots_groups(text)
        star = crawl._rules_for(groups, "*")
        if ("disallow", "/") in star:
            problems.append("robots.txt: the generated file blocks the whole site for *.")
        if not any(k == "sitemap" for _, rules in groups for k, _ in rules):
            problems.append("robots.txt: no Sitemap: directive in the generated file.")
        if any(a.lower() == "anthropic-ai" for agents, _ in groups for a in agents):
            problems.append("robots.txt: the deprecated anthropic-ai agent was emitted.")
        if any(re.search(r"\.(css|js)|/assets|/static", v, re.I)
               for k, v in star if k == "disallow"):
            problems.append("robots.txt: the generated file blocks CSS or JS.")

    sm = (outdir / "sitemap.xml")
    if sm.exists():
        text = sm.read_text(encoding="utf-8")
        if "<priority>" in text or "<changefreq>" in text:
            problems.append("sitemap.xml: priority/changefreq emitted, and Google ignores both.")
        if "<loc>" not in text:
            problems.append("sitemap.xml: no URLs. Nothing on the site qualified, which is "
                            "itself the finding - do not ship an empty sitemap.")
        if "INCOMPLETE - DO NOT DEPLOY" in text:
            problems.append(
                "sitemap.xml: generated from a capped crawl, so it is a subset of the site. "
                "Deploying it would drop every URL the crawl never reached. Re-crawl with a "
                "higher --max-pages and regenerate. (Header comment has the exact command.)")

    for f in ("organization.jsonld", "breadcrumbs.jsonld"):
        p = outdir / f
        if p.exists():
            try:
                json.loads(p.read_text(encoding="utf-8"))
            except json.JSONDecodeError as exc:
                problems.append(f"{f}: not valid JSON ({exc}).")
    return problems


